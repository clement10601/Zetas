class Q:
    def __init__(s, S=1):
        s.S = S; s.cv = Canvas(360*S, 480*S, seed_of("qmock"))
    def p(s, pts): return [(x*s.S, y*s.S) for x, y in pts]
    def fill(s, pts, color, ol=2.6, shade=0.28, n=2, alpha=1.0, side=1):
        cv = s.cv; P = chaikin(s.p(pts), n); m = cv.poly(P, 0.6)
        cv.paint(m, color, alpha)
        if shade:
            xs = [q[0] for q in P]
            x0, x1 = min(xs), max(xs); cut = x0 + (x1 - x0) * 0.3
            sh = hramp(m, cut + 1.5 * s.S, cut - 1.5 * s.S, 0.0, 1.0)
            cv.paint(cv.textured(sh, 0.18, "cloud"), mix(color, (60, 70, 110), 0.22), min(1.0, shade * 2.6) * alpha)
        if ol: cv.stroke(P + [P[0]], ol*s.S, mix(color, INK, 0.72), 0.95*alpha, dry=0.0, jitter=0.04, taper=(0.03, 0.05), smooth=0)
        return m
    def line(s, pts, w, color=INK, alpha=0.9, **kw): s.cv.stroke(s.p(pts), w*s.S, color, alpha, **kw)
    def ell(s, cx, cy, rx, ry, color, alpha=1.0, blur=0.5, angle=0.0):
        S = s.S; s.cv.paint(s.cv.ellipse(cx*S, cy*S, rx*S, ry*S, blur=blur*S, angle=angle), color, alpha)

